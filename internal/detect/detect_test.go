package detect

import "testing"

func TestClassify(t *testing.T) {
	cases := []struct {
		name  string
		pr    PR
		kind  Kind
		agent string
	}{
		{"copilot app", PR{Login: "Copilot", UserType: "Bot", HeadRef: "copilot/fix-123"}, Agent, "Copilot"},
		{"human on copilot branch is still human", PR{Login: "bryanchen-d", UserType: "User", HeadRef: "copilot/feature"}, Human, ""},
		{"codex cloud under user account", PR{Login: "alice", UserType: "User", Body: "Fixes #1\n\nhttps://chatgpt.com/codex/tasks/task_e_abc"}, Agent, "Codex"},
		{"claude code footer", PR{Login: "bob", UserType: "User", Body: "Summary\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"}, Agent, "Claude Code"},
		{"claude code web footer", PR{Login: "bob", UserType: "User", Body: "---\n_Generated by [Claude Code](https://claude.ai/code/session_01XYZ)_"}, Agent, "Claude Code"},
		{"claude app", PR{Login: "claude[bot]", UserType: "Bot"}, Agent, "Claude Code"},
		{"cursor background agent", PR{Login: "carol", UserType: "User", Body: `<a href="https://cursor.com/agents?id=bc-1"><img alt="Open in Cursor" src="https://cursor.com/assets/images/open-in-cursor-dark.png"></a>`}, Agent, "Cursor"},
		{"devin app", PR{Login: "devin-ai-integration[bot]", UserType: "Bot"}, Agent, "Devin"},
		{"devin review badge on human PR is not authorship", PR{Login: "dave", UserType: "User", Body: `<img src="https://static.devin.ai/assets/gh-devin-review-light.svg" alt="Devin Review">`}, Human, ""},
		{"jules", PR{Login: "google-labs-jules[bot]", UserType: "Bot"}, Agent, "Jules"},
		{"dependabot", PR{Login: "dependabot[bot]", UserType: "Bot"}, DepsBot, ""},
		{"renovate", PR{Login: "renovate[bot]", UserType: "Bot"}, DepsBot, ""},
		{"release bot", PR{Login: "github-actions[bot]", UserType: "Bot"}, OtherBot, ""},
		{"plain human", PR{Login: "octocat", UserType: "User", Body: "I used claude for ideas"}, Human, ""},
		{"case-insensitive login", PR{Login: "Kiro-Agent[bot]", UserType: "Bot"}, Agent, "Kiro"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := Classify(c.pr)
			if got.Kind != c.kind || got.Agent != c.agent {
				t.Fatalf("got %+v, want kind=%s agent=%q", got, c.kind, c.agent)
			}
		})
	}
}

