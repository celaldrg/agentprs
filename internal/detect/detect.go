// Package detect decides who opened a pull request: a named AI coding agent,
// a dependency bot, some other automation, or a human.
//
// It only trusts signatures the tools leave on purpose: the GitHub App that
// opened the PR, or a link/footer the agent writes into the PR body. It never
// guesses from writing style.
package detect

import "strings"

// Kind is the broad class of a PR author.
type Kind string

const (
	Agent    Kind = "agent"
	Human    Kind = "human"
	DepsBot  Kind = "deps"
	OtherBot Kind = "bot"
)

// PR is the subset of a GitHub pull request that detection needs.
type PR struct {
	Login    string // author login, e.g. "Copilot", "dependabot[bot]", "octocat"
	UserType string // "User" or "Bot"
	HeadRef  string // source branch
	Body     string
}

// Result is the classification of one PR.
type Result struct {
	Kind     Kind
	Agent    string // display name when Kind == Agent
	Evidence string // short, human-readable reason
}

// AgentRule describes how one agent signs its pull requests.
type AgentRule struct {
	Name    string
	Logins  []string // exact author logins (case-insensitive)
	Markers []string // substrings in the PR body (case-insensitive)
}

// Agents is the list of agents agentprs recognises, in match order.
var Agents = []AgentRule{
	{Name: "Copilot", Logins: []string{"copilot", "copilot-swe-agent[bot]", "copilot-swe-agent"}},
	{Name: "Codex", Logins: []string{"chatgpt-codex-connector[bot]"}, Markers: []string{"chatgpt.com/codex/tasks/"}},
	{Name: "Claude Code", Logins: []string{"claude[bot]", "claude"}, Markers: []string{
		"generated with [claude code]", "generated by [claude code]", "generated with claude code",
		"claude.ai/code/session_", "co-authored-by: claude <noreply@anthropic.com>",
	}},
	{Name: "Cursor", Logins: []string{"cursor[bot]", "cursor-agent[bot]"}, Markers: []string{
		"cursor.com/agents", "cursor.com/background-agent", "open-in-cursor-dark.png",
	}},
	{Name: "Devin", Logins: []string{"devin-ai-integration[bot]"}, Markers: []string{"app.devin.ai/sessions/", "devinenterprise.com/sessions/"}},
	{Name: "Jules", Logins: []string{"google-labs-jules[bot]"}, Markers: []string{"pr created automatically by jules", "jules.google.com/task/"}},
	{Name: "Kiro", Logins: []string{"kiro-agent[bot]"}},
	{Name: "Amazon Q", Logins: []string{"amazon-q-developer[bot]"}},
	{Name: "Factory", Logins: []string{"factory-droid[bot]"}},
	{Name: "cto.new", Logins: []string{"cto-new[bot]"}},
	{Name: "Codegen", Logins: []string{"codegen-sh[bot]"}},
	{Name: "CodeRabbit", Logins: []string{"coderabbitai[bot]"}},
	{Name: "OpenHands", Logins: []string{"openhands-agent", "openhands-ai[bot]"}, Markers: []string{"co-authored-by: openhands <openhands@all-hands.dev>"}},
	{Name: "Sweep", Logins: []string{"sweep-ai[bot]"}},
}

// DepsBots open dependency-update PRs. They are reported separately so they
// don't dilute the human baseline.
var DepsBots = []string{
	"dependabot[bot]", "dependabot-preview[bot]", "renovate[bot]", "renovate-bot", "pre-commit-ci[bot]",
	"snyk-bot", "greenkeeper[bot]", "depfu[bot]", "mend-for-github-com[bot]", "pyup-bot", "scala-steward",
}

// Classify returns who opened the PR.
func Classify(p PR) Result {
	login := strings.ToLower(strings.TrimSpace(p.Login))
	body := strings.ToLower(p.Body)

	// 1) The GitHub App that opened the PR is the strongest signal.
	for _, a := range Agents {
		for _, l := range a.Logins {
			if login == l {
				return Result{Kind: Agent, Agent: a.Name, Evidence: "opened by @" + p.Login}
			}
		}
	}
	for _, d := range DepsBots {
		if login == d {
			return Result{Kind: DepsBot, Evidence: "opened by @" + p.Login}
		}
	}
	// 2) A footer or task link the agent writes into the body. This catches
	// cloud agents that open the PR under the human's account (Codex, Cursor,
	// Claude Code on the web).
	for _, a := range Agents {
		if hasMarker(body, a) {
			return Result{Kind: Agent, Agent: a.Name, Evidence: "agent signature in PR body"}
		}
	}
	if strings.EqualFold(p.UserType, "Bot") || strings.HasSuffix(login, "[bot]") {
		return Result{Kind: OtherBot, Evidence: "opened by @" + p.Login}
	}
	return Result{Kind: Human}
}

func hasMarker(body string, a AgentRule) bool {
	for _, m := range a.Markers {
		if strings.Contains(body, m) {
			return true
		}
	}
	return false
}

// Names returns every agent name in match order.
func Names() []string {
	out := make([]string, len(Agents))
	for i, a := range Agents {
		out[i] = a.Name
	}
	return out
}
